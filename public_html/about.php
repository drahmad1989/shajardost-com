                <h2 class="section-title">Our Story</h2>
                <p>ShajarDost, which literally translates to "Friend of Trees," began its journey in 2011 as a small group of passionate individuals under the name <strong>Green Seekers</strong>. What started as a local initiative in Phool Nagar, District Kasur, has grown into one of Pakistan's most impactful grassroots environmental movements.</p>
                <p>Our founder, <strong>Muhammad Ahmad Baloch (Tipu)</strong>, envisioned a Pakistan where every citizen takes responsibility for the environment. His vision was simple yet powerful: if every person plants and cares for trees, Pakistan can become green again. This philosophy became the foundation of ShajarDost.</p>
                <p>In 2018, we launched the <strong>Ten Billion Trees Project (TBTP)</strong>, two months before the government's national initiative. This alignment amplified our impact, allowing us to combine grassroots energy with national policy. On 14th August 2018, we set a <strong>national record by planting 630,000 trees in a single day</strong>, proving that community-driven action can achieve extraordinary results.</p>
                <p>Today, ShajarDost operates across multiple cities in Punjab with dedicated teams, Green Scouts programs in schools, Mini Nursery projects, and Miyawaki Forest installations. We continue to grow, driven by the belief that every tree planted is a step toward a healthier, more sustainable Pakistan.</p>
