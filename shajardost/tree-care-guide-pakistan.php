<section class="section-padding">
    <div class="container">
        <div class="text-center"><h2 class="section-title">Common Tree Care Problems in Pakistan</h2><p class="section-desc">Identifying and addressing these common issues early can save your trees and ensure healthy growth for years to come.</p></div>
        <div class="grid-2">
            <div class="card fade-in"><div class="card-content">
                <h4><i class="fas fa-exclamation-triangle" style="color:#e74c3c;"></i> Overwatering</h4>
                <p>Yellowing leaves, root rot, and fungal growth are signs of overwatering. Ensure proper drainage and let the soil dry slightly between waterings. Pakistani soil can be clay-heavy and hold water longer than expected.</p>
            </div></div>
            <div class="card fade-in"><div class="card-content">
                <h4><i class="fas fa-exclamation-triangle" style="color:#e74c3c;"></i> Underwatering</h4>
                <p>Wilting, dry and crispy leaves, and slow growth indicate insufficient water. During Pakistan's extreme summers, young trees may need watering twice daily. Always check soil moisture before watering.</p>
            </div></div>
            <div class="card fade-in"><div class="card-content">
                <h4><i class="fas fa-bug" style="color:var(--gold);"></i> Pest Infestation</h4>
                <p>Common pests include aphids, mealybugs, and termites. Use neem oil as a natural pesticide. Regular inspection of leaves and trunk helps catch infestations early before they spread to other trees.</p>
            </div></div>
            <div class="card fade-in"><div class="card-content">
                <h4><i class="fas fa-wind" style="color:var(--secondary);"></i> Weather Damage</h4>
